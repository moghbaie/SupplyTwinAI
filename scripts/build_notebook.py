def build(colab: bool) -> list[dict]:
    intro = COLAB_INTRO if colab else INTRO
    cells = [md(intro.format(commit=commit())), md("## Setup")]
    cells.append(code(COLAB_SETUP if colab else SETUP))
    for title, note, files in GROUPS:
        cells.append(md(f"## Files: {title}\n{note}"))
        for f in files:
            text = Path(f).read_text(encoding="utf-8").replace("\r\n", "\n")
            cell = code("")
            cell["source"] = f"%%writefile {f}\n{text}".splitlines(True)  # keep final newline
            cells.append(cell)
    runs = [*RUNS[:2], *COLAB_DATA, *RUNS[4:]] if colab else RUNS
    return [*cells, md("## Install and helpers"), code(INSTALL), code(HELPERS), *runs]


def write(path: Path, cells: list[dict], colab: bool) -> None:
    meta: dict = {
        "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
        "language_info": {"name": "python"},
    }
    if colab:
        meta["colab"] = {"provenance": [], "toc_visible": True}
    nb = {"cells": cells, "metadata": meta, "nbformat": 4, "nbformat_minor": 5}
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(nb, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {path}: {len(cells)} cells")


def main() -> None:
    write(OUT, build(colab=False), colab=False)
    write(OUT_COLAB, build(colab=True), colab=True)


if __name__ == "__main__":
    main()
